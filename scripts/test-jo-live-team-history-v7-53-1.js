const fs = require('fs');
const vm = require('vm');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');
global.window = {};
vm.runInThisContext(read('js/jo-live-team-history-v7-53-1.js'), { filename: 'js/jo-live-team-history-v7-53-1.js' });
const api = window.WPI_JO_LIVE_HISTORY;
if (!api || api.release !== '7.53.1') throw new Error('JO live history module did not load');
const t = api._test;
const csv = `Date,Time,Type,Location,Gm #,White,S,Dark,S,W to #,L to #,GMID\n7/23/2026,8:00 AM,Group A,Pool 1,1,A1(1)-KERN PREMIER,9,A2(8)-ALPHA,5,3,4,16B-001\n7/23/2026,9:00 AM,Group B,Pool 1,2,B1(2)-BETA,8,B2(7)-GAMMA,6,,,16B-002\n7/24/2026,10:00 AM,Quarterfinal,Pool 2,3,W1-,10,W2-,7,,,16B-003\n7/24/2026,11:00 AM,Placement,Pool 2,4,L1-,6,L2-,5,,,16B-004\n7/25/2026,12:00 PM,Semifinal,Pool 3,5,W3-,11,A3(9)-DELTA,8,,,16B-005`;
const rows = t.parseCSV(csv);
const parsed = t.parseRows(rows);
if (parsed.length !== 5) throw new Error(`Expected 5 parsed games, found ${parsed.length}`);
const resolved = t.resolveTournament(parsed);
const quarter = resolved.games.find(game => String(game.game) === '3');
if (!quarter || quarter.whiteTeam !== 'Kern Premier' || quarter.darkTeam !== 'Beta') throw new Error('Winner route resolution failed');
const teamGames = resolved.games.map(game => t.gameForTeam(game, 'Kern Premier')).filter(Boolean);
if (teamGames.length !== 3) throw new Error(`Expected 3 Kern Premier games, found ${teamGames.length}`);
if (teamGames[0].result !== 'W' || teamGames[1].result !== 'W' || teamGames[2].result !== 'W') throw new Error('Team-perspective results are incorrect');
if (!t.configForProfile({ divisionId: '16u-boys-championship' })) throw new Error('Boys JO source configuration missing');
if (!t.configForProfile({ divisionId: '18u-girls-classic' })) throw new Error('Girls JO source configuration missing');
console.log('JO LIVE TEAM HISTORY 7.53.1 TESTS PASSED');
console.log(' - CSV parsing, W/L route resolution, team perspective, and source mapping are protected');
