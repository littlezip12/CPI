'use strict';
const fs=require('fs');
const path=require('path');
const assert=require('assert');
const ROOT=path.resolve(__dirname,'..');
const adapter=require(path.join(ROOT,'js/ecc-google-live-v7-64-42.js'));
const bundle=JSON.parse(fs.readFileSync(path.join(ROOT,'data/tournaments/platform/events/2026-evan-cousineau-memorial-cup.json'),'utf8'));
const csv=fs.readFileSync(path.join(ROOT,'data/tournaments/source/2026-evan-cousineau-memorial-cup/google-master-by-division-2026-10-03.csv'),'utf8');
const rows=adapter.parseRows(adapter.parseCSV(csv));
const validation=adapter.validateSource(rows,bundle);
assert.strictEqual(validation.gameCount,335);
assert.strictEqual(validation.divisionCount,13);
assert(validation.finalGameCount>=40,'fixture should contain tournament-day results');
assert.strictEqual(adapter.normalizeGameNumber('10Cptag01'),'10CPT01');
const merged=adapter.mergeBundle(bundle,rows,{method:'offline_fixture',fetchedAt:'2026-10-03T18:00:00Z'});
assert.strictEqual(merged.games.length,335);
assert.strictEqual(merged.divisions.length,13);
assert.strictEqual(merged.capabilities.scoreSourceStatus,'official_google_live_results');
assert.strictEqual(merged.liveSource.sheetName,'MASTER BY DIVISION');
const byNumber=new Map(merged.games.map(g=>[adapter.normalizeGameNumber(g.gameNumber),g]));
const hsg03=byNumber.get('HSG03');
assert(hsg03,'HSG03 missing');
assert.strictEqual(hsg03.status,'final');
assert.strictEqual(hsg03.scores.white,5);
assert.strictEqual(hsg03.scores.dark,3);
assert.strictEqual(hsg03.white.name,'MID VALLEY');
assert.strictEqual(hsg03.dark.name,'PV OVAC');
assert.strictEqual(hsg03.outcome.winnerName,'MID VALLEY');
const hsg08=byNumber.get('HSG08');
assert(hsg08,'HSG08 missing');
assert.strictEqual(hsg08.white.name,'MID VALLEY');
assert.strictEqual(hsg08.dark.name,'HONOLULU');
const lam=byNumber.get('14BPT01');
assert(lam,'14Bpt01 missing');
assert.strictEqual(lam.status,'final');
assert.strictEqual(lam.white.name.toUpperCase(),'LAMORINDA A');
assert.strictEqual(lam.scores.white,13);
assert.strictEqual(lam.scores.dark,11);
assert(!merged.teams.some(t=>t.divisionId==='hs-girls'&&t.name==='SD ECA'),'stale HS Girls team should be removed from live team list');
assert(merged.teams.some(t=>t.divisionId==='hs-girls'&&t.name==='MID VALLEY'),'MID VALLEY should be synthesized from official live source');
assert(merged.teams.some(t=>t.divisionId==='12u-boys-gold'&&t.name==='680 BLUE'),'official rename should be displayed');
assert.strictEqual(merged.summary.teamCount,162);
assert.strictEqual(merged.summary.finalGameCount,validation.finalGameCount);
console.log('WPHQ 7.64.42 ECC Google live adapter test passed.');
console.log(`- ${validation.gameCount}/335 stable game IDs`);
console.log(`- ${validation.divisionCount}/13 divisions`);
console.log(`- ${validation.finalGameCount} official results in fixture`);
console.log(`- ${merged.summary.teamCount}/162 live teams reconciled`);
